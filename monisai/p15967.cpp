//前缀和+小根堆（反向优先队列）前缀和+反悔贪心
//priority_queue<ll,vector<ll>,greater<ll>>q！！！priority_queue<ll,vector<ll>,greater<ll>>q！！priority_queue<ll,vector<ll>,greater<ll>>！
#include<bits/stdc++.h>
using namespace std;
typedef long long ll;
ll n,m,k;

ll c[100005];
ll sumc[100005];
ll kuang[100005];
int main (){
    cin>>n>>m>>k;
    sumc[1]=0;
    for(int i=1;i<n;i++){
        cin>>c[i];
    }
    for(int i=2;i<=n;i++){
        sumc[i]=sumc[i-1]+c[i-1];
    }
    for(int i=1;i<=n;i++){
        cin>>kuang[i];
    }
    priority_queue<ll,vector<ll>,greater<ll>>q;//优先队列保证第一个丢的是最小的
    ll sum=0;//记录采的矿
    ll ans=0;//记录最终答案
    for(int i=1;i<=n;i++){
        if(sumc[i]>m)break;
        ll rest=m-sumc[i];//坐完矿车剩下的，可以拿来开矿的钱
        q.push(kuang[i]);//将每堆的矿数入队
        sum+=kuang[i];
        while (q.size()>k){
            sum-=q.top();//采多了丢掉最小堆
            q.pop();
        }
        ans=max(ans,min(sum,rest));
        /*因为 sum 只是你“已经挑选出来的矿堆总容量”，但不代表你真的能采到这么多。

题目要满足两个限制：

最多从 k 个矿井里采矿
采矿总花费不能超过剩余钱 rest
所以当前状态能采到的实际矿石数量，是：

如果 sum <= rest，那你能全部采完，实际采 sum
如果 sum > rest，你最多只能花掉 rest 钱，实际采 rest
因此当前状态的可行采矿量是 min(sum, rest)，而不是 sum。

ans 记录的是“历史上见过的最大可行采矿量”，所以应该写成：

ans = max(ans, min(sum, rest));

如果直接用 ans = max(ans, sum)，当 sum > rest 时就会把不可能的结果当成答案。例如选了三个矿井总容量 250，但你剩下的钱只有 20，实际最多只能采 20。

所以最后 ans 要取“大”的那个可行值，但这个“大值x”本身必须先用 min(sum, rest) 变成“实际能采到”的数量。*/
    }
    cout<<ans;
}
